let hasError = false

for (const [ns, content] of Object.entries(dictionaries)) {
  const enKeys = Object.keys(content.en).sort()
  const filKeys = Object.keys(content.fil).sort()

  const enFile = path.join(localesEnDir, `${ns}.json`)
  const filFile = path.join(localesFilDir, `${ns}.json`)

  fs.writeFileSync(enFile, JSON.stringify(content.en, null, 2) + '\n', 'utf8')
  fs.writeFileSync(filFile, JSON.stringify(content.fil, null, 2) + '\n', 'utf8')

  // verify parity
  for (const k of enKeys) {
    if (!(k in content.fil)) {
      console.error(`[ERROR] Namespace ${ns}: key "${k}" in en but missing in fil`)
      hasError = true
    } else if (!content.en[k] || !content.fil[k]) {
      console.error(`[ERROR] Namespace ${ns}: key "${k}" has empty value`)
      hasError = true
    }
  }
  for (const k of filKeys) {
    if (!(k in content.en)) {
      console.error(`[ERROR] Namespace ${ns}: key "${k}" in fil but missing in en`)
      hasError = true
    }
  }
}

if (hasError) {
  process.exit(1)
} else {
  console.log(`✅ Successfully generated and verified ${Object.keys(dictionaries).length} locale namespaces for en and fil!`)
}
